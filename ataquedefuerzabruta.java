package eerciciosrepaso.src.ejerciciosrepaso;

public class ataquedefuerzabruta {
    public static void main(String[] args) {
        int n = 44;

        // Operadores de asignación compuesta
        n += 77; // n = n + 77
        System.out.println("Incrementada = " + n);

        n -= 3; // n = n - 3
        System.out.println("Decrementada = " + n);

        n *= 2; // n = n * 2
        System.out.println("Duplicada = " + n);
    }
}

